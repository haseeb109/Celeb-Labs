# audio/music.py — background music: licensed tracks from assets/music/ (listed in
# LICENSES.csv: file,title,artist,license,url), looped with 3 s crossfades; optional ai33 Suno.
# If the library is empty, a quiet synthesized drone pad is generated (no license needed).
from __future__ import annotations

import csv

import numpy as np

from ..constants import AUDIO_RATE as SR
from ..paths import ASSETS
from ..util import ffmpeg


def library() -> list[dict]:
    lic = ASSETS / "music" / "LICENSES.csv"
    if not lic.exists():
        return []
    rows = []
    with open(lic, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            p = ASSETS / "music" / r.get("file", "")
            if r.get("file") and p.exists() and r.get("license"):
                rows.append(r | {"path": str(p)})
    return rows


def decode(path: str, work_dir) -> np.ndarray:
    out = work_dir / "music_decoded.f32"
    ffmpeg(["-i", path, "-ar", str(SR), "-ac", "2", "-f", "f32le", str(out)])
    return np.fromfile(out, np.float32).reshape(-1, 2)


def drone(seconds: float, seed=11) -> np.ndarray:
    n = int(seconds * SR)
    t = np.arange(n, dtype=np.float32) / SR
    base = [55.0, 82.41, 110.0, 164.81]
    y = np.zeros(n, np.float32)
    for k, f in enumerate(base):
        lfo = 0.6 + 0.4 * np.sin(2 * np.pi * (0.03 + 0.01 * k) * t + k)
        y += np.sin(2 * np.pi * f * t + 0.3 * np.sin(2 * np.pi * 0.2 * t)) * lfo / (k + 1.5)
    y *= 0.18
    st = np.stack([y, np.roll(y, 240)], 1)
    return st.astype(np.float32)


def bed(seconds: float, work_dir, mood: str = "") -> tuple[np.ndarray, list[str]]:
    tracks = library()
    n = int(seconds * SR)
    if not tracks:
        return drone(seconds), ["Music: ambient pad generated by N Labs (no third-party music)"]
    out = np.zeros((n, 2), np.float32)
    pos, credits, xf = 0, [], int(3 * SR)
    k = 0
    while pos < n:
        tr = tracks[k % len(tracks)]
        a = decode(tr["path"], work_dir)
        if len(a) < xf * 2:
            break
        seg = a[: n - pos + xf]
        if pos > 0:
            fade = np.linspace(0, 1, xf, dtype=np.float32)[:, None]
            m = min(xf, len(seg), n - pos + xf)
            out[pos - xf:pos - xf + m] = out[pos - xf:pos - xf + m] * (1 - fade[:m]) + seg[:m] * fade[:m]
            seg = seg[m:]
            start = pos - xf + m
        else:
            start = 0
        end = min(n, start + len(seg))
        out[start:end] = seg[: end - start]
        pos = end
        c = f"Music: \"{tr.get('title')}\" by {tr.get('artist')} — {tr.get('license')} {tr.get('url', '')}".strip()
        if c not in credits:
            credits.append(c)
        k += 1
    return out, credits
